"""Country names — any spelling we have stored in, one name per language out.

The Country field in pictures holds whatever was typed or geocoded over the years
(Netherlands / Nederland / Holland, UK / England, USA / Verenigde Staten van
Amerika, a typo or two). Those files are never rewritten. Instead every spelling
resolves to an ISO code via assets/countries.csv, and the code to the name for the
reader's language.

Invariant: an unknown spelling is passed through UNCHANGED — never blanked, never
guessed — and inventory() lists it, so a new country or spelling is visible.

The CSV is generated by tools/svr_make_countries.py (edit OURS there, not the CSV).
See docs/plans/country_names_plan.md.
"""

import csv
import unicodedata
from functools import lru_cache
from pathlib import Path

_CSV = Path(__file__).resolve().parent.parent / "assets" / "countries.csv"
LANGS = ("en", "nl")


def _fold(text: str) -> str:
    """Match key: case-, accent- and spacing-insensitive (Belgie = België)."""
    t = unicodedata.normalize("NFKD", (text or "").replace("’", "'"))
    t = "".join(c for c in t if not unicodedata.combining(c))
    return " ".join(t.casefold().split())


@lru_cache(maxsize=1)
def _table():
    """({iso: {"en","nl","note"}}, {folded spelling: (iso, how)}).
    `how` is "name" for an en/nl display name, "alias" for anything else."""
    by_iso, by_name = {}, {}
    with _CSV.open(encoding="utf-8", newline="") as f:
        for r in csv.DictReader(f):
            iso = r["iso"]
            by_iso[iso] = {"en": r["en"], "nl": r["nl"], "note": r["note"]}
            for a in filter(None, (r["aliases"] or "").split(";")):
                by_name.setdefault(_fold(a), (iso, "alias"))
            for n in (r["en"], r["nl"], iso):   # display names win over aliases
                by_name[_fold(n)] = (iso, "name")
    return by_iso, by_name


def iso_of(text: str) -> str:
    """'Zuid-Afrika' → 'ZA'. '' when the text is empty or unknown."""
    hit = _table()[1].get(_fold(text))
    return hit[0] if hit else ""


def country_name(text: str, lang: str = "en") -> str:
    """The display name of a stored Country (or ISO code) in `lang` ('en'/'nl').
    Unknown text comes back unchanged; empty stays empty."""
    iso = iso_of(text)
    if not iso:
        return text or ""
    names = _table()[0][iso]
    return names.get(lang) or names["en"]


def gui_language(profile: str = "") -> str:
    """'en' or 'nl' for the app's own windows: the first of the two in a names
    profile (sci_en → en, nl_sci → nl). A window with its own Names: combo passes
    that profile; otherwise the global Preferred names setting is used."""
    from utils.name_profile import effective_profile, _chain
    return next((c for c in _chain(profile or effective_profile()) if c in LANGS), "en")


def inventory(counts: dict) -> list:
    """{stored Country: n pictures} → rows (stored, n, iso, how, en, note), unknown
    first, then by count. `how` = name / alias / unknown. Empty values are left out."""
    by_iso, by_name = _table()
    rows = []
    for stored, n in counts.items():
        if not (stored or "").strip():
            continue
        iso, how = by_name.get(_fold(stored), ("", "unknown"))
        info = by_iso.get(iso, {})
        note = info.get("note", "")             # a note names the spelling it explains
        note = note if _fold(stored) in _fold(note) else ""
        rows.append((stored, n, iso, how, info.get("en", ""), note))
    rows.sort(key=lambda r: (r[3] != "unknown", -r[1], r[0]))
    return rows
