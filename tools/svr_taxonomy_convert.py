"""Ch.6 — convert a (throw-away) master to the new species list. FIRST TEST.

Dry run by default: prints what it would do and touches nothing.
  --apply   do it: moves species folders to their new place, moves every
            generated web page (*.html) in biota/ to <master>/.trash/, rewrites
            speciescollection.csv, species.csv, data_pictures.csv and
            data_files.csv (backups first), logs every step.
  --undo L  put everything back from log L (moves reversed, CSVs restored).

Refuses a master inside Dropbox or registered as a main master. The tables come
from svr_taxonomy_build.py run on THIS master (taxa.csv, changes.csv).

Not done here (the code steps after this test): the app writing Sequence back,
aliases in the lookups, trips/albums that point into the master, website
redirects. The web pages are regenerated by rebuilding the website.

    python tools/svr_taxonomy_convert.py --master C:/SpeciesViewer/Taxonomy/nature \
        --tables D:/code/taxonomy_trial_greece [--apply | --undo <log>]
"""
import argparse
import ast
import csv
import datetime
import glob
import os
import shutil
import sys
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "speciesviewer"))

RANK_VALUE = {"species": 1, "family": 2, "order": 3, "class": 4, "phylum": 5, "kingdom": 6, "biota": 7}
GROUP_COLUMN = ["Species", "Family", "Order", "Class", "Phylum", "Kingdom", "Biota"]
COUNTS = ["iSpeciesThisRunCount", "iSpeciesCollectionCount", "iPictureThisRunCount",
          "iPictureCollectionCount", "iPicturesWithJPGsThisRun", "iPicturesWithJPGsCollection"]


def read_csv(path):
    with open(path, encoding="utf-8", newline="") as f:
        r = csv.DictReader(f, delimiter=";")
        return r.fieldnames, list(r)


def write_csv(path, header, rows):
    tmp = str(path) + ".tmp"
    with open(tmp, "w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(f, fieldnames=header, delimiter=";", extrasaction="ignore")
        w.writeheader()
        w.writerows(rows)
    os.replace(tmp, path)


def first(cell):
    v = ast.literal_eval(cell) if cell else []
    return v[0] if v else ""


def refuse_unsafe(root):
    if "dropbox" in str(root).lower():
        sys.exit(f"Refused: {root} is inside Dropbox. This test runs on a throw-away master only.")
    from utils.ini_io import read_ini
    import configparser
    cfg_dir = Path(os.environ.get("LOCALAPPDATA", "")) / "SpeciesViewer" / "config"
    for ini in glob.glob(str(cfg_dir / "sv_config_*.ini")):
        cp = configparser.ConfigParser(interpolation=None)
        read_ini(cp, ini)
        for sec in cp.sections():
            main = cp[sec].get("masterbiotadatabase", "")
            if main and Path(main).resolve() == Path(root).resolve():
                sys.exit(f"Refused: {root} is the main master ({ini}).")


# ---------------------------------------------------------------- the plan
def plan(root, tables):
    active = root / "metadata" / "active"
    taxa = {r["ScientificName"]: r for r in read_csv(tables / "taxa.csv")[1]}
    change = {r["Today"]: r for r in read_csv(tables / "changes.csv")[1]}
    sp_header, sp_rows = read_csv(active / "species.csv")

    def up(name):
        """The parent in the app's tree. A subspecies is (for now) a species-level
        entry BESIDE its species: its parent there is the species' family."""
        t = taxa[name]
        return taxa[t["Parent"]]["Parent"] if t["Rank"] == "subspecies" else t["Parent"]

    def chain(name):                      # [(rank, name)] from kingdom down to name
        out = []
        while name in taxa:
            out.insert(0, (taxa[name]["Rank"], name))
            name = up(name)
        return out

    def path_of(name):
        if taxa[name]["Rank"] == "subspecies":      # pictures sit in the species folder
            name = taxa[name]["Parent"]
        return "biota/" + "/".join(n for _, n in chain(name)) + "/"

    species_map, dir_map, problems = {}, {}, []
    for r in sp_rows:
        if r["Level"] != "Level.SPECIES" or not r["TargetPath"].startswith("biota/"):
            continue
        old = r["ScientificName"]
        if old not in change:
            problems.append(f"{old}: not in the tables (build them on this master)")
            continue
        new = change[old]["New"]
        if new not in taxa:
            problems.append(f"{old} -> {new}: not in taxa.csv")
            continue
        species_map[old] = new
        dir_map[r["TargetPath"]] = path_of(new)

    # file moves: every file in a species folder; every web page goes to trash
    moves, trash, collisions = [], [], []
    taken = set()
    for old_rel, new_rel in dir_map.items():
        src_dir = root / old_rel
        if not src_dir.is_dir():
            problems.append(f"folder missing on disk: {old_rel}")
            continue
        for f in sorted(os.listdir(src_dir)):
            src = src_dir / f
            if src.is_dir():
                problems.append(f"sub-folder in a species folder, left alone: {src}")
                continue
            if f.lower().endswith(".html"):
                continue                       # collected below with all pages
            dst = root / new_rel / f
            key = str(dst).lower()
            if src.resolve() == dst.resolve():
                continue
            if key in taken or (dst.exists() and str(dst).lower() != str(src).lower()):
                collisions.append(f"{src} -> {dst}")
            taken.add(key)
            moves.append((src, dst))
    species_dirs = {str((root / d)).lower().rstrip("\\/") for d in dir_map}
    for dirpath, dirs, files in os.walk(root / "biota"):
        dirs[:] = [d for d in dirs if not d.startswith(".")]
        for f in files:
            p = Path(dirpath) / f
            if f.lower().endswith(".html"):
                trash.append(p)
            elif str(Path(dirpath)).lower().rstrip("\\/") not in species_dirs:
                problems.append(f"file outside a species folder, left alone: {p}")
    return {"taxa": taxa, "change": change, "species_map": species_map, "dir_map": dir_map,
            "moves": moves, "trash": trash, "collisions": collisions, "problems": problems,
            "chain": chain, "path_of": path_of, "up": up, "sp": (sp_header, sp_rows)}


# ---------------------------------------------------------------- CSV rewrites
def map_rel(rel, dir_map):
    """'biota/.../040 passeriformes/054 corvidae/corvus cornix/[file]' -> new."""
    norm = rel.replace("\\", "/")
    for old, new in dir_map.items():
        if norm.lower().startswith(old.lower()):
            return new + norm[len(old):]
    return None


def map_abs(value, root, dir_map, sep_dir=False):
    if not value:
        return value
    norm = value.replace("\\", "/")
    base = str(root).replace("\\", "/").rstrip("/") + "/"
    if not norm.lower().startswith(base.lower()):
        return value
    rel = norm[len(base):] + ("/" if sep_dir else "")
    new = map_rel(rel, dir_map)
    if new is None:
        return value
    if sep_dir:
        new = new.rstrip("/")
    out = base + new
    return out.replace("/", "\\") if "\\" in value else out


def shifted_groups(new_species, P):
    """Kingdom..Family exactly as projectlib writes them (one level up)."""
    taxa = P["taxa"]
    g = {c: "" for c in ("Kingdom", "Phylum", "Class", "Order", "Family")}
    fam = P["up"](new_species)
    g["Family"] = fam
    node = fam
    while node:
        up = taxa[node]["Parent"] if node in taxa else ""
        up = up or ("biota" if node in taxa else "")
        if not up:
            break
        rank = taxa[node]["Rank"] if node in taxa else "biota"
        col = GROUP_COLUMN[RANK_VALUE[rank] - 1]
        if col in g:
            g[col] = up
        node = up if up in taxa else ""
    return g


def rewrite_csvs(root, P):
    active = root / "metadata" / "active"
    taxa, smap, dmap = P["taxa"], P["species_map"], P["dir_map"]

    # speciescollection: from the tables, in today's columns + Sequence at the end
    sc_header, sc_rows = read_csv(active / "speciescollection.csv")
    keep = [r for r in sc_rows if r["Level"] in ("Level.BIOTA", "Level.TOPICS", "Level.TOPIC",
                                                    "Level.TOPICLEAF")]
    up = P["up"]
    kids = defaultdict(list)
    for n, t in taxa.items():
        kids[up(n) or "biota"].append(n)
    order = lambda names: sorted(names, key=lambda n: float(taxa[n]["Sequence"]))
    rows = []
    for r in keep:
        if r["Level"] == "Level.BIOTA":
            r = dict(r, Leaves=str(order(kids["biota"])))
        rows.append(dict(r, Sequence=""))
    for n, t in taxa.items():
        sub = t["Rank"] == "subspecies"
        rows.append({"Level": "Level.SPECIES" if sub else "Level." + t["Rank"].upper(),
                     "ScientificName": n,
                     "DutchName": first(t["DutchNames"]), "EnglishName": first(t["EnglishNames"]),
                     "Up": up(n) or "biota", "Leaves": str(order(kids[n])),
                     "Sequence": t["Sequence"], "SubspeciesOf": t["Parent"] if sub else ""})
    write_csv(active / "speciescollection.csv",
              [c for c in sc_header if c not in ("Sequence", "SubspeciesOf")]
              + ["Sequence", "SubspeciesOf"], rows)

    # data_pictures
    dp_header, dp_rows = read_csv(active / "data_pictures.csv")
    for r in dp_rows:
        old = r.get("WetSoortNaam", "")
        if old in smap:
            new = smap[old]
            r["WetSoortNaam"] = new
            r["NLSoortNaam"] = first(taxa[new]["DutchNames"]) or r["NLSoortNaam"]
            r["EngSoortNaam"] = first(taxa[new]["EnglishNames"]) or r["EngSoortNaam"]
            r.update(shifted_groups(new, P))
        for col in ("TargetPath", "BestJPGPathName"):
            m = map_rel(r.get(col, ""), dmap) if r.get(col) else None
            if m is not None:
                r[col] = m
    write_csv(active / "data_pictures.csv", dp_header, dp_rows)

    # data_files
    df_header, df_rows = read_csv(active / "data_files.csv")
    for r in df_rows:
        r["WindowsFileName"] = map_abs(r["WindowsFileName"], root, dmap)
        r["File:Directory"] = map_abs(r["File:Directory"], root, dmap, sep_dir=True)
    write_csv(active / "data_files.csv", df_header, df_rows)

    # species.csv: species rows mapped (and merged), higher rows recomputed
    sp_header, sp_rows = P["sp"]
    out, other = {}, []
    for r in sp_rows:
        old = r["ScientificName"]
        if r["Level"] == "Level.SPECIES" and old in smap:
            new = smap[old]
            r = dict(r)
            r.update(ScientificName=new, Up=up(new),
                     DutchName=first(taxa[new]["DutchNames"]) or r["DutchName"],
                     EnglishName=first(taxa[new]["EnglishNames"]) or r["EnglishName"],
                     TargetPath=P["path_of"](new))
            if r["BestJPGPathName"]:
                r["BestJPGPathName"] = map_rel(r["BestJPGPathName"], dmap) or r["BestJPGPathName"]
            if new in out:                    # a subspecies folding into its species
                a = out[new]
                for c in COUNTS:
                    a[c] = str(int(a[c] or 0) + int(r[c] or 0))
                a["JPGmap"] = str(ast.literal_eval(a["JPGmap"] or "[]") + ast.literal_eval(r["JPGmap"] or "[]"))
                if int(r["currentHighestRating"] or 0) > int(a["currentHighestRating"] or 0):
                    for c in ("currentHighestRating", "BestJPG", "BestUPN", "BestJPGPathName"):
                        a[c] = r[c]
            else:
                out[new] = r
        elif r["Level"] in ("Level.TOPICS", "Level.TOPIC", "Level.TOPICLEAF"):
            other.append(r)
    higher = {}
    for new, r in out.items():
        for rank, name in P["chain"](new)[:-1]:
            higher.setdefault(name, rank)
    present = defaultdict(list)
    for n in list(out) + list(higher):
        present[up(n) or "biota"].append(n)

    def agg(name, rank):
        kids_ = [agg(k, taxa[k]["Rank"]) if k in higher else out[k] for k in order(present[name])]
        row = {c: "" for c in sp_header}
        best = max(kids_, key=lambda k: int(k["currentHighestRating"] or 0))
        row.update(Level="Level." + rank.upper(), ScientificName=name,
                   DutchName=first(taxa[name]["DutchNames"]) if name in taxa else "biota",
                   EnglishName=first(taxa[name]["EnglishNames"]) if name in taxa else "biota",
                   Up=(up(name) or "biota") if name in taxa else "",
                   Leaves=str(order(present[name])), JPGmap="[]",
                   currentHighestRating=best["currentHighestRating"], BestJPG=best["BestJPG"],
                   BestUPN=best["BestUPN"], BestJPGPathName=best["BestJPGPathName"],
                   TargetPath=P["path_of"](name) if name in taxa else "biota/")
        for c in COUNTS:
            row[c] = str(sum(int(k[c] or 0) for k in kids_))
        built.append(row)
        return row
    built = []
    agg("biota", "biota")
    write_csv(active / "species.csv", sp_header, built[::-1] + list(out.values()) + other)


# ---------------------------------------------------------------- apply / undo
def apply(root, tables, P):
    stamp = datetime.datetime.now().strftime("%Y%m%d-%H%M%S")
    active = root / "metadata" / "active"
    backup = active / "backup" / f"pre-taxonomy-{stamp}"
    trash = root / ".trash" / f"taxonomy-{stamp}"
    log_path = root / "admin" / f"taxonomy_convert_{stamp}.csv"
    log_path.parent.mkdir(parents=True, exist_ok=True)
    with open(log_path, "w", encoding="utf-8", newline="") as lf:
        log = csv.writer(lf, delimiter=";")
        log.writerow(["Kind", "From", "To"])
        backup.mkdir(parents=True)
        for name in ("speciescollection.csv", "species.csv", "data_pictures.csv", "data_files.csv"):
            shutil.copy2(active / name, backup / name)
            log.writerow(["backup", active / name, backup / name])
        lf.flush()
        for src in P["trash"]:
            dst = trash / src.relative_to(root)
            dst.parent.mkdir(parents=True, exist_ok=True)
            os.replace(src, dst)
            log.writerow(["trash", src, dst])
        for src, dst in P["moves"]:
            dst.parent.mkdir(parents=True, exist_ok=True)
            os.replace(src, dst)
            log.writerow(["move", src, dst])
        lf.flush()
    rewrite_csvs(root, P)
    removed = remove_empty_dirs(root / "biota")
    print(f"Applied. {len(P['moves'])} files moved, {len(P['trash'])} web pages to {trash}, "
          f"{removed} empty folders removed.\nLog (for --undo): {log_path}")


def remove_empty_dirs(top):
    n = 0
    for dirpath, dirs, files in os.walk(top, topdown=False):
        if Path(dirpath) != Path(top) and not os.listdir(dirpath):
            os.rmdir(dirpath)
            n += 1
    return n


def undo(root, log_path):
    with open(log_path, encoding="utf-8", newline="") as f:
        steps = list(csv.DictReader(f, delimiter=";"))
    for s in reversed(steps):
        if s["Kind"] in ("move", "trash"):
            Path(s["From"]).parent.mkdir(parents=True, exist_ok=True)
            os.replace(s["To"], s["From"])
        elif s["Kind"] == "backup":
            shutil.copy2(s["To"], s["From"])
    removed = remove_empty_dirs(root / "biota")
    print(f"Undone from {log_path}: {sum(s['Kind'] != 'backup' for s in steps)} files put back, "
          f"4 CSVs restored, {removed} empty folders removed.")


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--master", required=True, help="the master's root folder (…/nature)")
    ap.add_argument("--tables", help="folder with taxa.csv and changes.csv for this master")
    ap.add_argument("--apply", action="store_true")
    ap.add_argument("--undo", metavar="LOG")
    a = ap.parse_args()
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    root = Path(a.master)
    refuse_unsafe(root)
    if a.undo:
        return undo(root, Path(a.undo))
    if not a.tables:
        sys.exit("--tables is required")
    P = plan(root, Path(a.tables))
    renamed = {o: n for o, n in P["species_map"].items() if o != n}
    print(f"{len(P['species_map'])} species folders, {len(renamed)} with a new name; "
          f"{len(P['moves'])} files to move, {len(P['trash'])} web pages to trash.")
    for o, n in sorted(renamed.items()):
        print(f"  name: {o} -> {n}")
    for o, n in list(P["dir_map"].items())[:5]:
        print(f"  e.g. {o}\n    -> {n}")
    for c in P["collisions"]:
        print(f"  COLLISION {c}")
    for p in P["problems"]:
        print(f"  NOTE {p}")
    if P["collisions"]:
        sys.exit("Stopped: collisions — nothing done.")
    if not a.apply:
        print("Dry run — nothing done. Add --apply to convert.")
        return 0
    apply(root, Path(a.tables), P)
    return 0


if __name__ == "__main__":
    sys.exit(main())
